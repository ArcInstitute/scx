//! Pinned reference fixtures for PFlog's NB overdispersion `α` (§7.14, ORG-7.21-4).
//!
//! # Why an external reference at all
//!
//! `estimate_alpha` had **three** implementations of one definition —
//! itself, a `reference_alpha` in `pflog_tests.rs`, and a numpy copy in
//! `pyscx/tests/test_accel_pflog.py` — and every test was one of them agreeing
//! with another. All three carried the same `var > mean` pre-filter, so all
//! three were wrong in the same way and none could see it. Agreement between
//! siblings is not evidence; the two re-implementations are deleted.
//!
//! # The reference here is the GENERATING PARAMETER
//!
//! This is the one module in the reference family whose oracle is not another
//! library's output. It is `α_true`: the dispersion the counts were simulated
//! from. Ground truth outranks any second implementation, and it is what the
//! review asked for — "add a test simulating NB(μ, α) with known α".
//!
//! | constant | source |
//! |---|---|
//! | [`A_ALPHA_TRUE`], [`B_ALPHA_TRUE`], [`C_ALPHA_OVER`] | the `α` passed to `numpy.random.Generator.negative_binomial` |
//! | `A_COUNTS`, `B_COUNTS`, `C_COUNTS` | that generator's draws, emitted as integer literals |
//! | [`A_TRUNCATED_ALPHA`], [`C_TRUNCATED_ALPHA`] | the **pre-fix** estimator, run on this exact matrix |
//! | [`A_REL_BAR`], [`B_REL_BAR`] | a quantile of the estimator's sampling spread under the same design |
//!
//! Two things that would quietly make this module self-referential, and are
//! therefore not done:
//!
//! * **No bar is calibrated against what SCX returns.** A tolerance set from
//!   "SCX's answer plus headroom" moves with any bug in SCX and the test keeps
//!   passing — the defect the first version of `wilcoxon_reference_values.rs`
//!   had. Each `*_REL_BAR` is a quantile over independent draws of the same
//!   `(n_cells, μ, α_true)` design, so it describes how wide one draw of this
//!   size can be and nothing about SCX.
//! * **`*_TRUNCATED_ALPHA` is a repulsion target.** Nothing asserts SCX equals
//!   it. The tests assert SCX is *closer to `α_true`* than it is. Its exactness
//!   is irrelevant, which is why computing it with the old formula is not a
//!   self-reference.
//!
//! # What the tolerance can and cannot do here, measured
//!
//! The truncation's bias and the estimator's own sampling spread are both
//! proportional to the per-gene MoM noise `√(2/(n−1))·(1/μ + α)`, so their ratio
//! is governed by the **gene count**, not the cell count. Two fixtures were
//! built and rejected by the generator's own premise checks before this one:
//!
//! | fixture tried | truncation bias | 99th-pct sampling spread | verdict |
//! |---|---|---|---|
//! | `α_true = 0.02` | 17% | **27%** | no honest tolerance separates them |
//! | `α_true = 0.002` | ~350% | ~140% | separates — but the pooled median lands at −3e−6, so the fixed estimator *falls back* and the arm tests nothing |
//!
//! Every regime where the bias is large is a regime where a matrix-wide `α` is
//! not determined by 50 cells. So on fixture A the separator is **not** the
//! tolerance: it is two exact facts about this matrix — the pool must hold every
//! gene with a mean, and the estimate must be at least [`A_SEPARATION`]× closer
//! to `α_true` than [`A_TRUNCATED_ALPHA`] is. [`A_REL_BAR`] stays as a
//! gross-breakage bound and `pflog_reference_tests.rs` has a test asserting the
//! bar *accepts* the truncated answer, so nobody deletes the exact arms
//! believing the tolerance covers them.
//!
//! Fixture B is where the tight accuracy claim lives, and fixture C states the
//! mechanism with no tolerance at all.
//!
//! # Regenerating
//!
//! ```text
//! .venv/bin/python benchmarks/scripts/generate_pflog_alpha_references.py
//! ```
//!
//! That script owns the fixtures *and* the expected values, so they cannot
//! drift, and it refuses to emit a fixture that has stopped supporting the claim
//! it is pinned for. Do not hand-edit a constant here.

