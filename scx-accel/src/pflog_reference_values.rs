// --- fixture -> ShardSource --------------------------------------------------

fn rows_of<const G: usize>(counts: &[[u16; G]]) -> Vec<Vec<f32>> {
    counts
        .iter()
        .map(|r| r.iter().map(|&c| c as f32).collect())
        .collect()
}

/// Split the fixture across two shards.
///
/// Two rather than one deliberately: `streaming_mean_var` accumulates `Σx` and
/// `Σx²` per shard and merges, so a single-shard source would leave the merge
/// — and therefore most of the code path `estimate_alpha` actually runs —
/// untested by these fixtures.
fn two_shard_source<const G: usize>(counts: &[[u16; G]]) -> MultiShardSource {
    let rows = rows_of(counts);
    let split = rows.len() / 2;
    let (head, tail) = rows.split_at(split);
    raw_source_from_shards(&[head, tail], G)
}

