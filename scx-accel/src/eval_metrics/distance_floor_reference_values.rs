// Measured, at generation time:
//   ‖x₀‖² = 6.3786e+08 over 32 f32 dims
//   row 0 -> row 1: exact d = 3.125000e-02 (d² = 9.765625e-04); the f32 expansion returned d² = 0.000000e+00
//   row 0 -> row 2: exact d = 6.250000e-02 (d² = 3.906250e-03); the f32 expansion returned d² = 0.000000e+00
//   max relative distance error on the resolvable pairs: 3.363e-06
//   mean pairwise distance (scipy, sklearn convention): 6.6637658348e+03
//   sklearn.metrics.pairwise_distances(...).mean() agrees: 6.6637658348e+03
//   row 0's third neighbour sits at 5.8137e+03, so the pinned set is robust
//   the 3-row cluster's mean pairwise distance is 3.6361583177e-02; the f32 expansion collapses every one of its pairs to 0.0, so that mean comes back as 0
// the fixture reaches the regime it is pinned for.
/// The fixture flattened row-major, for kernels that take a dense `&[f32]`.
pub fn floor_x() -> Vec<f32> {
    FLOOR_X.iter().flat_map(|r| r.iter().copied()).collect()
}

/// Just the planted cluster: row 0 and its two near-duplicates, the leading
/// [`FLOOR_CLUSTER_N_ROWS`] rows of the fixture.
///
/// Every pair in it is one the f32 expansion cannot resolve, so a mean over this
/// sub-matrix is dominated by the defect instead of diluted by 570 well-separated
/// pairs.
pub fn floor_cluster_x() -> Vec<f32> {
    FLOOR_X
        .iter()
        .take(FLOOR_CLUSTER_N_ROWS)
        .flat_map(|r| r.iter().copied())
        .collect()
}
