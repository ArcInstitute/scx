//! Large-norm f32 fixture for the gemm distance expansion (§7.12, ORG-7.21-5).
//!
//! # Why an external reference at all
//!
//! Both `crate::neighbors::cpu::build_knn_exact` and
//! [`super::distances::mean_pairwise_distance`] turn a Gram entry into a squared
//! distance with `‖a‖² + ‖b‖² − 2·a·b`. On the documented-default `dtype="f32"`
//! path that dot product is accumulated in f32 **at the scale of the norms**, so
//! for large-norm rows the difference is noise long before `d²` is small in
//! absolute terms — and the `.max(0.0)` clamp that followed made the bias
//! one-sided. `docs/scanpy.md` claims "f32 + gemm matches f64 + scalar" within a
//! stated tolerance; ORG-7.21-5 recorded a large-norm f32 fixture as the missing
//! evidence for that claim, and this is it.
//!
//! # Provenance
//!
//! | constant | source |
//! |---|---|
//! | `FLOOR_X` | half-integers from `numpy.random.Generator.integers`, exactly representable in f32 |
//! | [`FLOOR_PLANTED`] | the **construction**: one coordinate of row 0 raised by an exact power of two, so `d²` is exactly `2⁻¹⁰` / `2⁻⁸` |
//! | [`FLOOR_ROW0_NEAREST`], [`FLOOR_MEAN_PAIRWISE`] | `scipy.spatial.distance.cdist` in f64 |
//! | [`FLOOR_DIST_RTOL`] | the measured f32 relative error on the pairs the expansion *can* resolve, one decimal order over |
//!
//! # What the fixture reaches, measured
//!
//! `‖x₀‖² ≈ 6.4e8` over 32 f32 dims. The two planted pairs sit at `d² = 9.77e-4`
//! and `3.91e-3` — an order of magnitude apart — and the pre-fix expansion
//! returned **exactly 0.0 for both**: two different distances reporting as one,
//! and as zero. That is the defect, and it is why the assertions here are about
//! *distances* rather than about neighbour ordering.
//!
//! A first attempt at this fixture used integers under 140, where `Σ xᵢxⱼ` stays
//! inside f32's exactly-representable integer range and the expansion is
//! bit-exact; it would have pinned nothing. The generator now fails rather than
//! emit a fixture that does not reach the regime.
//!
//! # Neighbour order is deliberately not pinned
//!
//! Only row 0's nearest **set** is. The fixture's other rows have top-5 gaps
//! down to `3.4e-04` against distances of ~`7e3`, which is inside the f32
//! expansion's own noise (`3.4e-06` relative), so their ordering is not well
//! defined at this precision and pinning it would encode noise as behaviour.
//! Row 0's third neighbour sits at `5.81e3` against the planted `6.25e-2`, so
//! that one set is robust by a factor of ~10⁵.
//!
//! # Regenerating
//!
//! ```text
//! .venv/bin/python benchmarks/scripts/generate_distance_floor_references.py
//! ```
//!
//! Paste, then `cargo fmt` — the count rows are wider than rustfmt's line limit.\n//!\n//! The script refuses to emit a fixture whose planted pairs do not collapse, or
//! whose resolvable pairs do.

