// --- fixture -> kernel inputs ------------------------------------------------

fn flat(m: &[[f64; CE_N_GENES]]) -> Vec<f64> {
    m.iter().flat_map(|r| r.iter().copied()).collect()
}

/// cell-eval's pseudobulk means, row-major, control row included.
pub fn means_real() -> Vec<f64> {
    flat(&CE_MEANS_REAL)
}

/// As [`means_real`], for the predicted side.
pub fn means_pred() -> Vec<f64> {
    flat(&CE_MEANS_PRED)
}

/// Perturbation effects — `means[p] − means[control]` — for the scored rows
/// only, in [`CE_SCORED_NAMES`] order.
///
/// `compute_discrimination_score` documents its input as "pseudobulk means minus
/// control, already computed", and cell-eval derives the same difference from the
/// same means. Subtracting one pinned row from another is not a second
/// implementation of anything.
pub fn effects(means: &[[f64; CE_N_GENES]]) -> Vec<f64> {
    let ctrl = &means[CE_CTRL_IDX];
    let mut out = Vec::with_capacity((CE_N_ROWS - 1) * CE_N_GENES);
    for (i, row) in means.iter().enumerate() {
        if i == CE_CTRL_IDX {
            continue;
        }
        out.extend(row.iter().zip(ctrl.iter()).map(|(v, c)| v - c));
    }
    out
}

/// The real-side effects.
pub fn effects_real() -> Vec<f64> {
    effects(&CE_MEANS_REAL)
}

/// The predicted-side effects.
pub fn effects_pred() -> Vec<f64> {
    effects(&CE_MEANS_PRED)
}

/// Per-cell matrices, flattened row-major.
pub fn cells_real() -> Vec<f32> {
    CE_CELLS_REAL
        .iter()
        .flat_map(|r| r.iter().copied())
        .collect()
}

/// As [`cells_real`], for the predicted side.
pub fn cells_pred() -> Vec<f32> {
    CE_CELLS_PRED
        .iter()
        .flat_map(|r| r.iter().copied())
        .collect()
}

/// Per-cell group indices into [`CE_ROW_NAMES`].
pub fn cell_groups() -> Vec<u32> {
    CE_CELL_LABELS
        .iter()
        .map(|l| {
            CE_ROW_NAMES
                .iter()
                .position(|n| n == l)
                .expect("every cell label is one of the pseudobulk row names") as u32
        })
        .collect()
}

/// The fixture as CSR (`indptr`, `indices`, `data`), dropping zeros — the form
/// the knockdown kernels take.
pub fn cells_real_csr() -> (Vec<i64>, Vec<i32>, Vec<f32>) {
    let mut indptr = vec![0i64];
    let (mut indices, mut data) = (Vec::new(), Vec::new());
    for row in CE_CELLS_REAL.iter() {
        for (c, &v) in row.iter().enumerate() {
            if v != 0.0 {
                indices.push(c as i32);
                data.push(v);
            }
        }
        indptr.push(indices.len() as i64);
    }
    (indptr, indices, data)
}

/// Owned `String` vectors, since the kernels take `&[String]`.
pub fn owned(names: &[&str]) -> Vec<String> {
    names.iter().map(|s| s.to_string()).collect()
}
