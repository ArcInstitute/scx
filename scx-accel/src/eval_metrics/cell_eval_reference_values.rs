//! Pinned cell-eval / arc-bench reference values (ORG-7.21-4).
//!
//! # Why an external reference at all
//!
//! `docs/scanpy/accel-perturbation-metrics.md` claims the perturbation-evaluation
//! metrics are "numerically equivalent to the Python references within the
//! tolerances below", citing
//! `pyscx/tests/test_cell_eval_parity.py`. That file `importorskip`s
//! `cell_eval`, `arc_bench` and `polars`; **no conda env has them**, and CI's
//! Python-bindings job does not install them either. The claim rested on a local
//! run in a developer venv, and nothing automated could restate it.
//!
//! Across this directory exactly three external numbers were pinned before this
//! module: sklearn's AMI / NMI / ARI in [`super::clustering`]. Every other metric
//! was checked by hand-derivation from *reading* the reference implementation, or
//! by comparing two SCX code paths (f32 gemm against f64 scalar) — the "sibling
//! implementations agreeing" shape ORG-7.21-4 exists to retire.
//!
//! # Every value here was PRODUCED by cell-eval or arc-bench
//!
//! | table | source |
//! |---|---|
//! | [`CE_PEARSON_DELTA`], [`CE_MSE`], [`CE_MAE`], [`CE_MSE_DELTA`], [`CE_MAE_DELTA`] | `cell_eval.metrics._anndata.*` |
//! | `CE_DISCRIM_*` | `cell_eval.metrics._anndata.discrimination_score` |
//! | [`CE_EDISTANCE_CORR`] | `cell_eval.metrics._anndata.edistance` |
//! | [`CE_KD_BASELINE`], [`CE_KD_EFFICIENCY`], [`CE_KD_LOG_DEVIATION`], [`CE_KD_IS_NAN`] | `arc_bench.tools.normalize_transform.core.*` |
//! | `CE_MEANS_REAL` / `CE_MEANS_PRED` | `PerturbationAnndataPair::_bulk_anndata` |
//!
//! That last row is load-bearing. The pseudobulk means are taken from
//! cell-eval's own bulk step rather than recomputed, so the Rust kernel is handed
//! exactly the matrix cell-eval scored. Recomputing them would compare two
//! metrics over two slightly different inputs and call the difference a
//! tolerance.
//!
//! # Bars, and where they come from
//!
//! | field | bar | why |
//! |---|---|---|
//! | bulk metrics, knockdown | `CE_ATOL` + `CE_RTOL·\|want\|` = 1e-6 + 1e-7·\|want\| | see below |
//! | discrimination scores | `abs = 0` | an integer rank divided by `P`, so equality is exact or the ranking differs |
//! | e-distance correlation | [`CE_EDISTANCE_ATOL`] = 1e-4 | `docs/scanpy/accel-perturbation-metrics.md`'s documented tolerance: an O(N²) reduction whose order differs from sklearn's BLAS |
//!
//! Pinned **at** the documented bar and not tighter: a tighter pin would encode
//! behaviour the docs promise not to have.
//!
//! The relative term is not a widening. `docs/scanpy/accel-perturbation-metrics.md`
//! records these bars as
//! `atol=1e-6`, but the test they describe writes
//! `np.testing.assert_allclose(..., atol=1e-6)`, and **numpy's default `rtol` is
//! `1e-7`** — so the bar the pytest suite has always enforced is
//! `1e-6 + 1e-7·|want|`. The absolute half alone is not a magnitude-independent
//! claim and cannot be: cell-eval stores these in f32, so the divergence scales
//! with the value. Measured here, `mse_delta` for one perturbation is `23.0172`
//! and the two sides differ by `1.25e-6` — inside numpy's effective bar, outside
//! a bare `1e-6`. The docs table now states both components.
//!
//! # Two claims are deliberately not pinned
//!
//! * **Mixed-tie discrimination ranks** — `numpy.argsort`'s default kind is
//!   `quicksort`, which is not stable, so the reference's own tie behaviour is
//!   implementation-defined. `docs/scanpy/accel-perturbation-metrics.md` carves
//!   this out and
//!   `super::discrimination_cell_eval_tests` pins SCX's stable-argsort semantics
//!   as a deliberate divergence.
//! * **`clustering_agreement`** — Leiden is stochastic and the documented bar is
//!   an aggregate `atol=0.15`, which is not a number worth freezing.
//!
//! # Regenerating
//!
//! ```text
//! .venv/bin/python benchmarks/scripts/generate_eval_metrics_references.py
//! ```
//!
//! Then `cargo fmt`. The script owns the fixture *and* the expected values, and
//! refuses to emit a table whose metric came out constant across perturbations —
//! such a table is satisfied by any implementation returning that constant.

