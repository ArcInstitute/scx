"""Generate the large-norm f32 fixture for the gemm distance expansion (§7.12).

Run it from the repo root, in the uv venv — never system Python:

    .venv/bin/python benchmarks/scripts/generate_distance_floor_references.py

Paste the output into
`scx-accel/src/eval_metrics/distance_floor_reference_values.rs`.

## Why this fixture exists

`‖a‖² + ‖b‖² − 2·a·b` is how both the exact-kNN path (`neighbors/cpu.rs`) and
the blocked pairwise kernel (`eval_metrics/distances.rs`) turn a Gram entry into
a squared distance. The dot product is accumulated in the input's precision —
f32 on the documented-default `dtype="f32"` path — at the scale of the *norms*,
so for large-norm rows the difference is noise long before `d²` is small in
absolute terms, and the `.max(0.0)` clamp then makes the bias one-sided.
`docs/scanpy/accel-perturbation-metrics.md` claims "f32 + gemm matches f64 +
scalar within these bounds";
ORG-7.21-5 listed a large-norm f32 fixture as the missing evidence.

## The construction is the reference for the planted pairs

Every value is a half-integer, so it is exactly representable in f32 and the
f64 reference computed here is the same number the Rust kernel sees. Two rows
are copies of row 0 with a **single** coordinate raised by an exact power of
two, so their squared distances are exactly `2⁻¹⁰` and `2⁻⁸` — analytically, not
because something computed them.

The top-k tables come from `scipy.spatial.distance.cdist` in f64 — an outside
implementation, so the ordering claim does not rest on SCX agreeing with itself.

The magnitudes are chosen so the f32 dot product genuinely rounds: half-integers
in the thousands over 32 dims put `Σ x_i x_j` above f32's exactly-representable
integer range (2²⁴), which is the regime the review describes and which small
integer fixtures do **not** reach — a first attempt with values under 140 came
out bit-exact and would have pinned nothing.
"""

from __future__ import annotations

import os
import sys

import numpy as np

from _rust_literals import f64_literal, rust_matrix

N_ROWS, N_DIMS = 24, 32
VAL_LO, VAL_HI = 3000, 6000
SEED = 70101
# Row 0's near-duplicates: (row, coordinate, exponent of the separation).
PLANTED = ((1, 3, -5), (2, 7, -4))
# How many neighbours scipy is asked for. Only row 0's nearest two are pinned;
# see the note beside `FLOOR_ROW0_NEAREST` in main().
K = 5


def fixture() -> np.ndarray:
    rng = np.random.default_rng(SEED)
    x = rng.integers(VAL_LO * 2, VAL_HI * 2, size=(N_ROWS, N_DIMS)).astype(np.float64) / 2.0
    for row, coord, exp in PLANTED:
        x[row] = x[0].copy()
        x[row][coord] += 2.0**exp
    if not np.array_equal(x, x.astype(np.float32).astype(np.float64)):
        raise SystemExit("// the fixture is not exactly representable in f32")
    return x


def gemm_expansion_f32(x: np.ndarray) -> np.ndarray:
    """What the kernels computed before the fix: f32 gemm, f64 norms, clamp."""
    x32 = x.astype(np.float32)
    gram = (x32 @ x32.T).astype(np.float32)
    nrm = (x**2).sum(axis=1)
    d_sq = nrm[:, None] + nrm[None, :] - 2.0 * gram.astype(np.float64)
    return np.maximum(d_sq, 0.0)


def main() -> int:
    from importlib.metadata import version

    from scipy.spatial.distance import cdist
    from sklearn.metrics import pairwise_distances

    print(f"// numpy {version('numpy')}, scipy {version('scipy')}, scikit-learn {version('scikit-learn')}")
    print(f"// generated by benchmarks/scripts/{os.path.basename(__file__)}")
    print()

    x = fixture()
    exact = cdist(x, x, metric="euclidean")  # f64, scipy
    np.fill_diagonal(exact, np.inf)
    order = np.argsort(exact, axis=1, kind="stable")[:, :K]
    knn_dist = np.take_along_axis(exact, order, axis=1)

    failures: list[str] = []

    # The planted separations, analytic.
    planted_rows = [row for row, _, _ in PLANTED]
    planted_d = [2.0**exp for _, _, exp in PLANTED]
    for (row, _, exp), want in zip(PLANTED, planted_d):
        got = exact[0, row]
        if abs(got - want) > 0:
            failures.append(
                f"row 0 to row {row}: scipy says {got!r}, the construction says "
                f"{want!r} — the planted separation is not the only difference"
            )

    # The pre-fix expansion must actually lose them, or the fixture pins nothing.
    before = gemm_expansion_f32(x)
    for row, want in zip(planted_rows, planted_d):
        if before[0, row] != 0.0:
            failures.append(
                f"the f32 expansion returns {before[0, row]:.6e} for the pair at "
                f"d² = {want**2:.6e} rather than collapsing it to 0.0 — this "
                f"fixture no longer reaches the regime §7.12 describes"
            )
    if before[0, planted_rows[0]] != before[0, planted_rows[1]]:
        failures.append(
            "the f32 expansion still distinguishes the two planted pairs, so the "
            "fixture does not demonstrate two different distances reporting as one"
        )

    # A relative bar for the pairs the expansion CAN resolve. Every pair *within*
    # the planted cluster is excluded, not just the two involving row 0: rows 1
    # and 2 are each a one-coordinate perturbation of row 0, so they are near
    # duplicates of each other too and collapse the same way. Masking only
    # `(0, 1)` and `(0, 2)` left `(1, 2)` in the sample and reported a relative
    # error of exactly 1.0 — the check below caught it.
    cluster = [0, *planted_rows]
    mask = np.ones_like(exact, dtype=bool)
    np.fill_diagonal(mask, False)
    for i in cluster:
        for j in cluster:
            mask[i, j] = False
    with np.errstate(invalid="ignore"):
        rel = np.abs(np.sqrt(before) - exact)[mask] / exact[mask]
    rtol = float(np.max(rel))
    if rtol >= 1e-3:
        failures.append(
            f"the relative error on the pairs the expansion should resolve is "
            f"{rtol:.3e}; something outside the planted cluster is collapsing too "
            f"and the bar would be meaningless"
        )

    # Row 0's two nearest neighbours, per scipy. Pinned as a SET, and only for
    # row 0: the fixture's other rows have top-k gaps down to 3.4e-04 against
    # distances of ~1e4, which is inside the f32 expansion's own noise, so their
    # neighbour ORDER is not well defined and pinning it would encode noise
    # rather than behaviour.
    # The first `len(cluster)` rows of the fixture ARE the cluster (row 0 and its
    # two planted near-duplicates), so a sub-matrix of the leading rows is enough
    # for the blocked kernel to be dominated by pairs the f32 expansion loses.
    # Without this, reverting the fix in `eval_metrics/distances.rs` leaves every
    # assertion in the file green — the 24-row mean moves by 2 pairs in 576.
    if sorted(cluster) != list(range(len(cluster))):
        failures.append(
            f"the planted cluster is {sorted(cluster)}, not the leading rows, so "
            f"a leading sub-matrix is not the cluster"
        )
    cl = exact[: len(cluster), : len(cluster)].copy()
    np.fill_diagonal(cl, 0.0)
    cluster_mean = float(cl.mean())
    sk_cl = float(
        pairwise_distances(x[: len(cluster)], x[: len(cluster)], metric="euclidean").mean()
    )
    if abs(sk_cl - cluster_mean) / cluster_mean > 1e-12:
        failures.append(f"scipy {cluster_mean!r} vs sklearn {sk_cl!r} on the cluster mean")

    row0_nearest = sorted(int(v) for v in order[0, :2])
    if row0_nearest != sorted(planted_rows):
        failures.append(
            f"row 0's two nearest are {row0_nearest}, not the planted "
            f"{sorted(planted_rows)} — the fixture's construction no longer holds"
        )
    third = float(exact[0, order[0, 2]])
    if third <= 100.0 * planted_d[-1]:
        failures.append(
            f"row 0's third neighbour is at {third:.3e}, too close to the planted "
            f"{planted_d[-1]:.3e} for the set to be robust"
        )
    # `mean_pairwise_distance_self` documents its convention as
    # `sum(d(i,j) for i<j) * 2 / (n*n)` — sklearn's
    # `pairwise_distances(a, a).mean()`, which forces the self diagonal to 0
    # rather than evaluating it. A first version of this reference averaged over
    # the off-diagonal entries only and disagreed by exactly 552/576; the number
    # below is the documented convention, cross-checked against the library the
    # doc names.
    exact_zero_diag = exact.copy()
    np.fill_diagonal(exact_zero_diag, 0.0)
    mean_pairwise = float(exact_zero_diag.mean())
    sk = float(pairwise_distances(x, x, metric="euclidean").mean())
    if abs(sk - mean_pairwise) / mean_pairwise > 1e-12:
        failures.append(
            f"scipy says {mean_pairwise!r} and sklearn says {sk!r} for the same "
            f"mean; the convention this reference pins is no longer the one the "
            f"kernel documents"
        )

    print(f"pub const FLOOR_N_ROWS: usize = {N_ROWS};")
    print(f"pub const FLOOR_N_DIMS: usize = {N_DIMS};")
    print(f"pub const FLOOR_DIST_RTOL: f64 = {f64_literal(float(f'{rtol * 10:.3g}'))};")
    print(f"pub const FLOOR_MEAN_PAIRWISE: f64 = {f64_literal(mean_pairwise)};")
    print(f"pub const FLOOR_CLUSTER_N_ROWS: usize = {len(cluster)};")
    print(f"pub const FLOOR_CLUSTER_MEAN_PAIRWISE: f64 = {f64_literal(cluster_mean)};")
    print(
        "pub const FLOOR_ROW0_NEAREST: [usize; 2] = ["
        + ", ".join(str(v) for v in row0_nearest)
        + "];"
    )
    print()
    print("/// Row 0's planted near-duplicates and their exact distances.")
    print(
        "pub const FLOOR_PLANTED: [(usize, f64); 2] = ["
        + ", ".join(f"({row}, {f64_literal(d)})" for row, d in zip(planted_rows, planted_d))
        + "];")
    print()
    print(rust_matrix("FLOOR_X", x, ty="f32"))
    print()
    print("// Measured, at generation time:")
    print(f"//   ‖x₀‖² = {(x[0] ** 2).sum():.4e} over {N_DIMS} f32 dims")
    for row, want in zip(planted_rows, planted_d):
        print(
            f"//   row 0 -> row {row}: exact d = {want:.6e} (d² = {want**2:.6e}); "
            f"the f32 expansion returned d² = {before[0, row]:.6e}"
        )
    print(f"//   max relative distance error on the resolvable pairs: {rtol:.3e}")
    print(f"//   mean pairwise distance (scipy, sklearn convention): {mean_pairwise:.10e}")
    print(f"//   sklearn.metrics.pairwise_distances(...).mean() agrees: {sk:.10e}")
    print(f"//   row 0's third neighbour sits at {third:.4e}, so the pinned set is robust")
    print(
        f"//   the {len(cluster)}-row cluster's mean pairwise distance is "
        f"{cluster_mean:.10e}; the f32 expansion collapses every one of its pairs "
        f"to 0.0, so that mean comes back as 0"
    )

    if failures:
        raise SystemExit(
            "// the fixture no longer supports the claims it is pinned for:\n  "
            + "\n  ".join(failures)
        )
    print("// the fixture reaches the regime it is pinned for.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
